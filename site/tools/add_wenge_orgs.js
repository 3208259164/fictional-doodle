/* 文革图谱整个文件包在 IIFE 里（前面有 reuse()、补籍贯等逻辑），末尾才是
   window.SITE_GRAPH_WENGE={...} 一整行。所以要两步：
   ① 整文件 vm 执行，拿到最终对象（IIFE 里的加工也一并生效）
   ② 只替换末尾那一行赋值，前面的逻辑与注释原样保留 */
const vm = require('vm');
function loadAndPrepare(file) {
  const s = fs.readFileSync(file, 'utf8');
  const sb = { window: {} }; sb.window.window = sb.window;
  vm.createContext(sb);
  vm.runInContext(s, sb, { filename: 'graph-wenge.js' });
  const G = sb.window.SITE_GRAPH_WENGE;
  const k = s.lastIndexOf('window.SITE_GRAPH_WENGE');
  const lb = s.indexOf('{', k);
  let depth = 0, inStr = false, esc = false, end = -1;
  for (let i = lb; i < s.length; i++) {
    const c = s[i];
    if (inStr) {
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === '"') inStr = false;
    } else {
      if (c === '"') inStr = true;
      else if (c === '{') depth++;
      else if (c === '}') { depth--; if (depth === 0) { end = i; break; } }
    }
  }
  return { head: s.slice(0, lb), tail: s.slice(end + 1), G };
}
