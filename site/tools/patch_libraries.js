/* ---------- 读写 ---------- */
/* data/libraries.js 是 JS 对象字面量（单引号、键不加引号），不是 JSON，
   直接 JSON.parse 会在第一个字符就报错。用 vm 执行取结果。 */
const vm = require('vm');
function load() {
  const src = fs.readFileSync(FILE, 'utf8');
  const i = src.indexOf('window.SITE_LIBRARIES');
  const sb = { window: {} }; sb.window.window = sb.window;
  vm.createContext(sb);
  vm.runInContext(src.slice(i), sb, { filename: 'libraries.js' });
  return { head: src.slice(0, i), L: sb.window.SITE_LIBRARIES || [] };
}
const { head, L } = load();

let introN = 0;
L.forEach(it => {
  if (INTRO[it.id] && it.note !== INTRO[it.id]) { it.note = INTRO[it.id]; introN++; }
});

let addN = 0, skipN = 0;
NEW.forEach(n => {
  if (L.some(x => x.id === n.id) || L.some(x => x.url === n.url)) { skipN++; return; }
  L.push({ id: n.id, group: n.group, name: n.name, url: n.url, search: '', tag: n.tag, note: n.note });
  addN++;
});

fs.writeFileSync(FILE, head + 'window.SITE_LIBRARIES = ' + JSON.stringify(L, null, 2) + ';\n');

/* 自检：不删、不重复、介绍长度 */
